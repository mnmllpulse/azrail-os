-- AZRAIL — модели, подключённые вручную.
--
-- ЗАЧЕМ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ ПРАВКА src/lib/model-registry.ts
--
-- Реестр в коде держится на правиле: в него попадает только то, что
-- подтверждено в каталоге Cloudflare, и у каждой записи есть поле source.
-- Правило заведено не из аккуратности: слаг @cf/meta/llama-3.1-8b-instruct
-- однажды вписали по памяти, он оказался снятым с поддержки, и
-- классификатор намерений работал бы на мёртвой модели.
--
-- Модель, добавленная владельцем через интерфейс, по определению НЕ
-- подтверждена сверкой с каталогом. Класть её в тот же массив — значит
-- стереть границу между проверенным и добавленным на слово, то есть
-- вернуть ровно ту ошибку, от которой реестр защищает.
--
-- Поэтому две разные сущности лежат в двух разных местах, а объединяются
-- только на чтение (lib/custom-models.ts → effectiveRegistry), и каждая
-- запись отсюда всегда помечена как добавленная вручную.
--
-- ПОЛЕ source ОБЯЗАТЕЛЬНО И ЗДЕСЬ. Через полгода вопрос «откуда взялась
-- эта строка и что в ней перепроверять» возникнет одинаково и к реестру,
-- и к ручной записи. Пустая строка не принимается проверкой в коде.

CREATE TABLE IF NOT EXISTS custom_models (
  slug TEXT PRIMARY KEY,
  provider TEXT NOT NULL,
  tier TEXT NOT NULL CHECK (tier IN ('frontier','balanced','fast')),
  -- JSON-массив возможностей. Состав проверяется в коде: перечень
  -- ModelCapability живёт в TypeScript, и дублировать его здесь строкой
  -- значило бы завести второй источник правды, который разойдётся.
  capabilities TEXT NOT NULL,
  -- NULL = НЕ ПРОВЕРЕНО, а не «маленькое». Та же семантика, что в реестре:
  -- маршрутизатор по непроверенному окну не фильтрует.
  context_window INTEGER CHECK (context_window IS NULL OR context_window > 0),
  -- Вычисляется из слага, а не задаётся руками: во всём реестре
  -- requiresGateway строго равно «слаг не начинается с @cf/». Ручной ввод
  -- этого поля добавил бы способ сломать вызов опечаткой в галочке.
  requires_gateway INTEGER NOT NULL CHECK (requires_gateway IN (0,1)),
  source TEXT NOT NULL,
  created_at INTEGER NOT NULL,
  created_by TEXT NOT NULL
);
