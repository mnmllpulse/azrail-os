// AZRAIL — лимиты шагов миссии. Единственное место, где живут эти числа.
//
// Раньше «8» и «20» были вписаны литералами в пяти местах (лимит запросов,
// бюджет записей, роут миссии, цикл исполнения, промпт планировщика).
// Поменяй одно — остальные молча расходятся: лимит списывает 8 единиц,
// а цикл крутит 12.

/**
 * Шагов по умолчанию, если вызывающий не указал.
 *
 * Было 8. Почему поднято до 12: план сам по себе занимал до 8 шагов
 * (промпт планировщика требовал «не больше min(max, 8)»), то есть при
 * дефолте 8 на исправление ошибки, повтор после syntax-guard или
 * перечитывание файла не оставалось НИ ОДНОГО шага. Первая же осечка
 * гарантированно заканчивалась mission.exhausted. 12 — это потолок
 * планировщика (MAX_STEPS в planner.ts) и тот же порядок, что 8 + запас.
 */
export const DEFAULT_MISSION_ITERATIONS = 12;

/** Жёсткий потолок. Даже если попросили больше — зациклившаяся модель
 *  иначе крутилась бы до исчерпания лимитов Worker'а. */
export const MAX_MISSION_ITERATIONS = 20;

/** Сколько шагов реально получит миссия. Единая формула для всех мест. */
export function clampIterations(asked: unknown): number {
  const n = Number(asked);
  const base = Number.isFinite(n) && n > 0 ? Math.floor(n) : DEFAULT_MISSION_ITERATIONS;
  return Math.max(1, Math.min(base, MAX_MISSION_ITERATIONS));
}

/** Потолок шагов ПЛАНА внутри бюджета миссии.
 *
 *  План не должен съедать весь бюджет: четверть оставляется на исправления
 *  и повторы. При 12 шагах — план до 9, запас 3. При 4 — план 3, запас 1.
 *  Верх 12 совпадает с MAX_STEPS планировщика. */
export function planStepCap(maxIterations: number): number {
  return Math.max(1, Math.min(12, Math.floor(maxIterations * 0.75)));
}
