// AZRAIL — что человек хочет, по глаголу, а не по мнению модели.
//
// ЗАЧЕМ. Классификация свободного текста шла ТОЛЬКО через модель, и промпт
// описывал answer, generate_ui, security_scan, qa_check, evolution_audit —
// а generate_code не описывал ВООБЩЕ. Самое частое намерение у одиночного
// разработчика — «напиши файл», «создай страницу» — не было объяснено, и
// дешёвая модель выбирала из того, что ей растолковали. «Визитка с тремя
// ссылками» уезжала в qa_check, QA-агент искал существующие модули для
// анализа покрытия, не находил их в пустом проекте и честно отказывался:
// «Не найдено исходных модулей». Со стороны это выглядело как отказ
// работать по нормальной задаче.
//
// ПОЧЕМУ ДО МОДЕЛИ. Глагол «создай» — не предмет для рассуждения. Там, где
// намерение читается по форме фразы, вызов модели добавляет только шанс
// ошибиться. Быстрые проверки уже есть выше (gitOp, inputType); эта — того
// же рода, просто по тексту.
//
// ГРАНИЦЫ. Разбор НАМЕРЕННО узкий: он отвечает только когда уверен, и
// молчит во всех спорных случаях, отдавая их модели. Агрессивный разбор по
// ключевым словам хуже модели: он ошибается так же, но молча и всегда
// одинаково.

/** Что вернул разбор. null — «не знаю, спрашивай модель». */
export type QuickIntent = "generate_code" | "generate_ui" | "answer" | null;

/* ГРАНИЦЫ СЛОВ С КИРИЛЛИЦЕЙ.
 *
 * \b в JavaScript опирается на \w, а \w — это ASCII. Для русского текста
 * граница никогда не срабатывает, и первая версия этих правил не находила
 * ВООБЩЕ НИЧЕГО: разбор молча возвращал null на каждую фразу и был бы
 * бесполезен, оставшись незамеченным. Поймано тестом сразу.
 *
 * Поэтому: смотрим назад на «не букву» через \p{L} с флагом u, а вперёд не
 * смотрим — сопоставляем основы слова, чтобы «создай», «создать» и
 * «создайте» ловились одним правилом. */
const NB = "(?<!\\p{L})";

/** Просьба создать/изменить файлы: глагол действия над кодом. */
const CREATE_RE = new RegExp(
  NB +
    "(созда(й|ть|йте)|напиш(и|ите)|написать|сдела(й|ть|йте)|сгенерируй|собери|собрать|" +
    "добав(ь|ить|ьте)|исправ(ь|ить|ьте)|почин(и|ить)|перепиш(и|ите)|переписать|" +
    "реализ(уй|овать)|внеси|допиши)",
  "iu",
);

/** Признаки интерфейсной работы. Проверяются ТОЛЬКО вместе с глаголом
 *  создания: «что такое вёрстка» — вопрос, а не задача на вёрстку. */
const UI_RE = new RegExp(
  NB + "(интерфейс|вёрстк|верстк|компонент|экран|страниц|визитк|лендинг|кнопк|дизайн|ui|html|css)",
  "iu",
);

/** Вопросительные формы. Ответом служит текст, а не изменение в проекте. */
const QUESTION_RE = new RegExp(
  NB +
    "(что такое|как работает|как устроен|почему|зачем|чем отлича|в чём разниц|в чем разниц|" +
    "объясни|расскажи|посоветуй|стоит ли|можно ли|какой лучше|сравни)",
  "iu",
);

/**
 * Слова, при которых разбор МОЛЧИТ, даже если глагол создания есть.
 *
 * «Создай тесты», «напиши аудит безопасности» — это специализированные
 * намерения со своими агентами, и решать тут должна модель. Без этого
 * списка узкий разбор перехватывал бы чужие задачи — то есть повторял бы
 * ошибку, которую призван исправить, только в другую сторону.
 */
const AMBIGUOUS_RE = new RegExp(
  NB + "(тест|покрыти|уязвимост|безопасн|секрет|аудит|деплой|задепло|выкат|коммит|ветк|pull request|пулл|merge|мёрдж)",
  "iu",
);

/**
 * Намерение по форме фразы. null означает «решает модель».
 *
 * Порядок проверок важен: сначала то, что запрещает отвечать, потом
 * вопрос, и только потом действие. Фраза «объясни, как создать компонент»
 * содержит и «объясни», и «создать» — это вопрос, а не задача.
 */
export function quickIntent(text: string): QuickIntent {
  const s = (text ?? "").trim();
  if (!s) return null;

  // Слишком длинный текст разбирать по словам бессмысленно: в нём найдётся
  // всё сразу. Это работа для модели.
  if (s.length > 600) return null;

  if (AMBIGUOUS_RE.test(s)) return null;

  const asksQuestion = QUESTION_RE.test(s) || s.trimEnd().endsWith("?");
  const wantsAction = CREATE_RE.test(s);

  // Вопрос выигрывает у действия: «как сделать X» — просьба объяснить.
  if (asksQuestion) return wantsAction ? null : "answer";

  if (!wantsAction) return null;

  return UI_RE.test(s) ? "generate_ui" : "generate_code";
}
