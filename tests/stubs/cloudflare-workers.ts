// Заглушка модуля `cloudflare:workers` для запуска тестов в обычном Node.
//
// Он существует только внутри рантайма Cloudflare, поэтому пакет `agents`
// (который его импортирует) в Node не грузится, а вместе с ним не грузится и
// весь граф импортов, включая реестр агентов.
//
// Заглушка НЕ имитирует поведение — она лишь позволяет модулям загрузиться,
// чтобы можно было проверить чистую логику: парсеры, фильтры, реестр.
// Ничего, что реально зависит от рантайма, здесь не тестируется, и это
// сознательное ограничение: такие вещи проверяются только на живом деплое.

export class DurableObject {
  ctx: unknown;
  env: unknown;
  constructor(ctx?: unknown, env?: unknown) {
    this.ctx = ctx;
    this.env = env;
  }
}

export class WorkflowEntrypoint {}

export const env = {};
